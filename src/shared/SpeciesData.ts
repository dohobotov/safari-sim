export function pickAnimalName(species: SpeciesId, sex: Sex, id: number): string {
  const pool = sex === 'M' ? NAMES_M[species] : NAMES_F[species];
  return pool[id % pool.length];
}

export function getSpeciesTitleRu(species: SpeciesId, sex: Sex): string {
  switch (species) {
    case 'elephant':
      return sex === 'M' ? 'Слон' : 'Слониха';
    case 'lion':
      return sex === 'M' ? 'Лев' : 'Львица';
    case 'tiger':
      return sex === 'M' ? 'Тигр' : 'Тигрица';
    case 'giraffe':
      return sex === 'M' ? 'Жираф' : 'Жирафа';
    case 'hippo':
      return sex === 'M' ? 'Бегемот' : 'Бегемотиха';
    case 'zebra':
      return 'Зебра';
    case 'antelope':
      return 'Антилопа';
    case 'deer':
      return sex === 'M' ? 'Олень' : 'Лань';
    case 'boar':
      return 'Кабан';
    case 'vulture':
      return 'Гриф';
  }
}
